from pathlib import Path
from PIL import Image
import json
p=Path('cozy/assets/sprites.mjs')
d=json.loads(p.read_text().split('export const SPRITES = ')[1].strip().rstrip(';'))
for key,w,y in [["desk",260,0.78],["chair",125,0.85],["wardrobe-oak",200,0.9],["bookshelf",200,0.89],["bed-cream",365,0.74],["drawers",158,0.87],["floor-lamp",86,0.89],["rug-moss",320,0.53],["mug",30,0.76],["vintage-lamp",52,0.82],["pothos",60,0.72],["book-stack",47,0.83],["candle",25,0.76],["laptop",87,0.84]]:
 a=Image.open('cozy/'+d[key]['master']).getchannel('A')
 b=a.point(lambda v:255 if v>40 else 0).getbbox()
 d[key]['width']=round(w/((b[2]-b[0])/a.width),3)
 d[key]['pivot']['y']=y
p.write_text('// Generated by tools/import-sprite.py. External raster art; no runtime generation.\nexport const SPRITES = '+json.dumps(d,indent=2)+';\n')
