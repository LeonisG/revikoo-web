"""Import an ImageGen PNG master; optimize its alpha-preserving web delivery.

Only encoding/resizing and alpha analysis happen here. No furniture is drawn,
recolored, mirrored, or generated procedurally. Artwork comes from ImageGen.
"""
import argparse
import json
import shutil
import os
import time
from pathlib import Path
from PIL import Image

parser = argparse.ArgumentParser()
parser.add_argument('source', type=Path)
parser.add_argument('id')
parser.add_argument('--collection', default='oak-cozy')
parser.add_argument('--category', default='furniture')
parser.add_argument('--width', type=float, required=True, help='Visible art width in world units')
parser.add_argument('--pivot-y', type=float, default=.82)
parser.add_argument('--pivot-x', type=float, default=.5)
parser.add_argument('--state', default='canonical')
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
stem = args.id + ('' if args.state == 'canonical' else '-' + args.state)
master = root / 'assets' / 'masters' / args.collection / (stem + '.png')
web = root / 'assets' / 'items' / args.collection / args.category / (stem + '.webp')
master.parent.mkdir(parents=True, exist_ok=True)
web.parent.mkdir(parents=True, exist_ok=True)
shutil.copy2(args.source, master)
im = Image.open(master).convert('RGBA')
alpha = im.getchannel('A')
assert alpha.getextrema()[0] == 0, 'Master must have real transparency'
bbox = alpha.point(lambda value: 255 if value > 40 else 0).getbbox()
assert bbox, 'Empty image'
# Keep the full master canvas and its normalized pivot; optimize without cropping.
im.thumbnail((768, 768), Image.Resampling.LANCZOS)
im.save(web, 'WEBP', quality=88, method=6, exact=True)
mask = im.getchannel('A').resize((32, 32), Image.Resampling.BOX)
bits = ''.join('1' if v > 40 else '0' for v in mask.tobytes())
mask_hex = ''.join(format(int(bits[i:i+4], 2), 'x') for i in range(0, len(bits), 4))
registry = root / 'assets' / 'sprites.mjs'
entry = {
    'src': web.relative_to(root / 'assets').as_posix(),
    'master': master.relative_to(root).as_posix(),
    'width': round(args.width / ((bbox[2]-bbox[0])/alpha.width), 3),
    'aspect': im.width/im.height,
    'pivot': {'x': args.pivot_x, 'y': args.pivot_y},
    'pixels': [im.width, im.height], 'bytes': web.stat().st_size,
    'hitMask': mask_hex,
}
lock = registry.with_suffix('.lock')
deadline = time.monotonic() + 30
while True:
    try:
        lock_fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
        break
    except FileExistsError:
        if time.monotonic() > deadline: raise TimeoutError('Sprite registry is locked')
        time.sleep(.05)
try:
    data = json.loads(registry.read_text(encoding='utf-8').split('export const SPRITES = ', 1)[1].strip().removesuffix(';'))
    if args.state == 'canonical': data[args.id] = {**data.get(args.id, {}), **entry}
    else: data.setdefault(args.id, {}).setdefault('states', {})[args.state] = entry
    temp = registry.with_suffix(f'.{os.getpid()}.tmp')
    temp.write_text('// Generated by tools/import-sprite.py. External raster art; no runtime generation.\nexport const SPRITES = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
    temp.replace(registry)
finally:
    os.close(lock_fd)
    lock.unlink()
print(json.dumps({'id': args.id, 'state': args.state, 'file': str(web), 'bytes': entry['bytes'], 'alpha': True}))
